"""Step 0: find past winners automatically from historical price data.

Pulls the most active Solana pools from GeckoTerminal, keeps tokens launched
within the look-back window, and checks each token's daily price history for
a big run (early low -> later peak). Writes them, with their peak price, to
winners_auto.txt for the discover step.
"""
import time
from collections import defaultdict

from . import config, gecko


def measure_run(candles, early_days=None):
    """From daily candles (oldest first) return (run_multiple, early_low, peak, peak_ts).

    early_low = lowest low in the first `early_days` days of trading.
    peak      = highest high after that low.
    """
    early_days = early_days or config.EARLY_DAYS
    if len(candles) < 2:
        return None
    first = candles[0][0]
    early = [c for c in candles if c[0] < first + early_days * 86400] or candles[:1]
    lows = [c for c in early if c[3] > 0]
    if not lows:
        return None
    low_c = min(lows, key=lambda c: c[3])
    after = [c for c in candles if c[0] >= low_c[0]]
    peak_c = max(after, key=lambda c: c[2])
    if peak_c[2] <= 0:
        return None
    return peak_c[2] / low_c[3], low_c[3], peak_c[2], int(peak_c[0])


def select(cands, cfg=config):
    """Pick the strongest runs, spread across launch weeks for variety."""
    cands = sorted(cands, key=lambda c: c["run"], reverse=True)
    per_week, out = defaultdict(int), []
    for c in cands:
        wk = c["created"] // (7 * 86400) if c["created"] else 0
        if per_week[wk] >= cfg.MAX_WINNERS_PER_WEEK:
            continue
        per_week[wk] += 1
        out.append(c)
        if len(out) >= cfg.MAX_WINNERS:
            break
    return out


def run(log=print, now=None):
    now = now or time.time()
    lo = now - config.WINNER_MAX_AGE_DAYS * 86400
    hi = now - config.WINNER_MIN_AGE_DAYS * 86400

    log("Collecting active Solana pools from GeckoTerminal (free API, ~10 calls/min)...")
    pools = gecko.top_pools(sort="h24_volume_usd_desc") + \
        gecko.top_pools(sort="h24_tx_count_desc") + gecko.trending_pools()
    best = {}
    for p in pools:
        m = p["base"]
        if not m or m in config.QUOTE_MINTS or p["quote"] not in config.QUOTE_MINTS:
            continue
        if not p["created"] or not (lo <= p["created"] <= hi):
            continue
        if m not in best or (p["liquidity"] or 0) > (best[m]["liquidity"] or 0):
            best[m] = p
    log(f"  {len(pools)} pools seen, {len(best)} tokens launched "
        f"{config.WINNER_MIN_AGE_DAYS:g}-{config.WINNER_MAX_AGE_DAYS:g} days ago. "
        f"Checking price history (~{len(best) * gecko.GAP_SECONDS / 60:.0f} min)...")

    cands = []
    for i, (m, p) in enumerate(best.items(), 1):
        if i % 10 == 0:
            log(f"  checked {i}/{len(best)}, {len(cands)} winners so far")
        r = measure_run(gecko.daily_ohlcv(p["pool"]))
        if not r:
            continue
        mult, low, peak, peak_ts = r
        now_px = p["price_usd"]
        size_now = p["mcap"] or p["fdv"]
        peak_size = size_now * peak / now_px if (size_now and now_px) else None
        if mult < config.MIN_RUN_MULTIPLE:
            continue
        if peak_size is not None and peak_size < config.MIN_PEAK_MCAP_USD:
            continue
        cands.append({"mint": m, "name": p["name"], "run": mult, "peak": peak,
                      "peak_ts": peak_ts, "created": p["created"], "peak_size": peak_size})

    chosen = select(cands)
    lines = ["# Auto-generated by `python main.py winners` on "
             + time.strftime("%Y-%m-%d", time.localtime(now)),
             "# mint  peak_price_usd  # name, run, launch -> peak"]
    for c in chosen:
        size = f", peak ~${c['peak_size'] / 1e6:.1f}M" if c["peak_size"] else ""
        lines.append(
            f"{c['mint']}  {c['peak']:.12g}  # {c['name']}: {c['run']:.0f}x{size}, "
            f"launched {time.strftime('%b %d', time.localtime(c['created']))}, "
            f"peak {time.strftime('%b %d', time.localtime(c['peak_ts']))}")
    with open(config.WINNERS_AUTO_FILE, "w") as f:
        f.write("\n".join(lines) + "\n")
    log(f"\n{len(chosen)} winners written to {config.WINNERS_AUTO_FILE}:")
    for line in lines[2:22]:
        log("  " + line.split("#", 1)[1].strip())
    log("\nNext: python main.py discover")
    return chosen
